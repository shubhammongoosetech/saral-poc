/**
 * DealerlessDkgParticipant.ts
 *
 * Sovereign Dealerless DKG Participant Node.
 * Executes HybridDKG (Kate, Huang, Goldberg 2012) in true dealerless fashion:
 *  - Samples its private polynomial locally
 *  - Distributes encrypted row shares to peers via ECDH / AES-256-GCM
 *  - Authenticates all outgoing and incoming messages with secp256k1 identity signatures
 *  - Decrypts received shares and verifies against peer commitments
 *  - Runs reliable broadcast and leader agreement
 *  - Aggregates its final share s_i strictly in local memory/vault
 *  - NEVER exposes its private share to the coordinator or network
 */

import { secp256k1 } from '@noble/curves/secp256k1';
import { DomainType } from '../types/domain';
import {
  HybridDkgNode,
  deriveHybridParams,
} from '../crypto/hybriddkg/hybridDkg';
import {
  EncryptedShareEnvelope,
  SignedProtocolEnvelope,
} from './types';
import {
  deriveEcdhKey,
  encryptPayloadGcm,
  decryptPayloadGcm,
  signDkgPayload,
  verifyDkgSignature,
} from './dkgCrypto';
import type {
  NodeConfig,
  OutgoingMessage,
  VssSendMsg,
  HybridDkgOutput,
} from '../crypto/hybriddkg/types';

export class DealerlessDkgParticipant {
  public readonly nodeId: string;
  public readonly domain: DomainType;
  public readonly nodeIndex: number;
  public readonly identityPublicKeyHex: string;
  private readonly identityPrivateKeyHex: string;
  public readonly sessionId: string;
  public readonly n: number;
  public readonly t: number;
  public readonly f: number;

  private dkgNode: HybridDkgNode;
  private peerPublicKeys: Map<number, string> = new Map();
  private localStoredShare: bigint | null = null;
  private isFinalized: boolean = false;
  private finalOutput: HybridDkgOutput | null = null;

  // Pending outgoing messages destined for router
  private pendingOutgoing: Array<EncryptedShareEnvelope | SignedProtocolEnvelope> = [];

  constructor(options: {
    nodeId: string;
    domain: DomainType;
    nodeIndex: number;
    identityPrivateKeyHex: string;
    sessionId: string;
    n: number;
    t?: number;
    f?: number;
    allNodeIds: string[];
    peerPublicKeys: Map<number, string>;
  }) {
    this.nodeId = options.nodeId;
    this.domain = options.domain;
    this.nodeIndex = options.nodeIndex;
    this.identityPrivateKeyHex = options.identityPrivateKeyHex;
    this.sessionId = options.sessionId;
    this.peerPublicKeys = options.peerPublicKeys;

    const cleanPriv = options.identityPrivateKeyHex.startsWith('0x')
      ? options.identityPrivateKeyHex.slice(2)
      : options.identityPrivateKeyHex;
    const pub = secp256k1.getPublicKey(cleanPriv, true);
    this.identityPublicKeyHex = Buffer.from(pub).toString('hex');

    const params = deriveHybridParams(options.n, options.t, options.f);
    this.n = params.n;
    this.t = params.t;
    this.f = params.f;

    const nodeConfig: NodeConfig = {
      n: params.n,
      t: params.t,
      f: params.f,
      nodeIndex: this.nodeIndex,
      nodeId: this.nodeId,
      domain: this.domain,
      sessionId: this.sessionId,
      allNodeIds: options.allNodeIds,
      peerPublicKeys: options.peerPublicKeys,
    };

    this.dkgNode = new HybridDkgNode(nodeConfig);
  }

  /**
   * Starts dealing this participant's polynomial contribution.
   * Encrypts each row polynomial a_j(y) under peer j's public key.
   */
  public startDealing(secret?: bigint): Array<EncryptedShareEnvelope | SignedProtocolEnvelope> {
    const rawOutgoing = this.dkgNode.startDealing(secret);
    const converted = this.processRawOutgoing(rawOutgoing);
    this.pendingOutgoing.push(...converted);
    return converted;
  }

  /**
   * Pulls pending outgoing envelopes generated by this participant.
   */
  public pollOutgoing(): Array<EncryptedShareEnvelope | SignedProtocolEnvelope> {
    const msgs = [...this.pendingOutgoing];
    this.pendingOutgoing = [];
    return msgs;
  }

  /**
   * Ingests an incoming encrypted share envelope from a peer.
   */
  public handleEncryptedShare(envelope: EncryptedShareEnvelope): Array<EncryptedShareEnvelope | SignedProtocolEnvelope> {
    if (envelope.sessionId !== this.sessionId || envelope.domain !== this.domain) {
      return [];
    }
    if (envelope.targetIndex !== this.nodeIndex) {
      return [];
    }

    // 1. Verify sender's signature
    const peerPub = this.peerPublicKeys.get(envelope.dealerIndex);
    if (!peerPub) {
      return [];
    }

    const payloadToVerify = `${envelope.sessionId}:${envelope.domain}:${envelope.dealerIndex}:${envelope.targetIndex}:${envelope.encryptedPayload}:${envelope.ivHex}:${envelope.authTagHex}`;
    if (!verifyDkgSignature(payloadToVerify, envelope.signatureHex, peerPub)) {
      return [];
    }

    // 2. Decrypt payload using ECDH
    try {
      const ecdhKey = deriveEcdhKey(this.identityPrivateKeyHex, peerPub, this.sessionId);
      const decryptedJson = decryptPayloadGcm(
        envelope.encryptedPayload,
        envelope.ivHex,
        envelope.authTagHex,
        ecdhKey
      );
      const { aCoeffs } = JSON.parse(decryptedJson);

      // 3. Construct internal VSS_SEND message and deliver to HybridDkgNode
      const vssSend: VssSendMsg = {
        type: 'VSS_SEND',
        sessionId: this.sessionId,
        domain: this.domain,
        dealerIndex: envelope.dealerIndex,
        targetIndex: this.nodeIndex,
        commitmentMatrix: envelope.commitmentMatrix,
        aCoeffs,
      };

      const rawOutgoing = this.dkgNode.handle(vssSend);
      const converted = this.processRawOutgoing(rawOutgoing);
      this.pendingOutgoing.push(...converted);
      this.checkCompletion();
      return converted;
    } catch {
      return [];
    }
  }

  /**
   * Ingests an incoming signed protocol envelope (ECHO, READY, PROPOSAL, LEAD_CH).
   */
  public handleProtocolMessage(envelope: SignedProtocolEnvelope): Array<EncryptedShareEnvelope | SignedProtocolEnvelope> {
    if (envelope.sessionId !== this.sessionId || envelope.domain !== this.domain) {
      return [];
    }
    if (envelope.targetIndex !== 'broadcast' && envelope.targetIndex !== this.nodeIndex) {
      return [];
    }

    // 1. Verify digital signature
    const senderPub = this.peerPublicKeys.get(envelope.fromIndex);
    if (!senderPub) {
      return [];
    }

    const payloadStr = JSON.stringify(envelope.payload);
    const hashMsg = `${envelope.sessionId}:${envelope.domain}:${envelope.fromIndex}:${payloadStr}`;
    if (!verifyDkgSignature(hashMsg, envelope.signatureHex, senderPub)) {
      return [];
    }

    // 2. Deliver to local HybridDkgNode state machine
    const rawOutgoing = this.dkgNode.handle(envelope.payload);
    const converted = this.processRawOutgoing(rawOutgoing);
    this.pendingOutgoing.push(...converted);
    this.checkCompletion();
    return converted;
  }

  /**
   * Advances the timer in the underlying HybridDkgNode.
   */
  public tickTimer(currentTime?: number): Array<EncryptedShareEnvelope | SignedProtocolEnvelope> {
    const rawOutgoing = this.dkgNode.checkTimer(currentTime);
    const converted = this.processRawOutgoing(rawOutgoing);
    this.pendingOutgoing.push(...converted);
    this.checkCompletion();
    return converted;
  }

  /**
   * Checks if local DKG has finalized and securely saves accumulated share.
   */
  private checkCompletion(): void {
    if (this.dkgNode.isComplete() && !this.isFinalized) {
      const out = this.dkgNode.getOutput();
      if (out) {
        this.isFinalized = true;
        this.finalOutput = out;
        // Securely save share in local memory
        this.localStoredShare = out.share;
      }
    }
  }

  public isComplete(): boolean {
    return this.isFinalized;
  }

  public getFinalPublicOutput(): {
    domain: DomainType;
    domainPublicKeyHex: string;
    commitments: string[];
    agreedQ: number[];
  } | null {
    if (!this.finalOutput) return null;
    return {
      domain: this.finalOutput.domain,
      domainPublicKeyHex: this.finalOutput.domainPublicKeyHex,
      commitments: this.finalOutput.commitments,
      agreedQ: this.finalOutput.Q,
    };
  }

  /**
   * Returns local share strictly for testing purposes.
   * In production, this share remains in the isolated vault.
   */
  public getLocalShareForTesting(): bigint | null {
    return this.localStoredShare;
  }

  /**
   * Converts raw outgoing HybridDkgNode messages into encrypted or signed wire envelopes.
   */
  private processRawOutgoing(rawList: OutgoingMessage[]): Array<EncryptedShareEnvelope | SignedProtocolEnvelope> {
    const envelopes: Array<EncryptedShareEnvelope | SignedProtocolEnvelope> = [];

    for (const item of rawList) {
      const msg = item.message;

      if (msg.type === 'VSS_SEND') {
        const targetIdx = msg.targetIndex;
        const targetPub = this.peerPublicKeys.get(targetIdx);
        if (!targetPub) continue;

        // Encrypt row coefficients under recipient's public key
        const ecdhKey = deriveEcdhKey(this.identityPrivateKeyHex, targetPub, this.sessionId);
        const payloadJson = JSON.stringify({ aCoeffs: msg.aCoeffs });
        const { ciphertextHex, ivHex, authTagHex } = encryptPayloadGcm(payloadJson, ecdhKey);

        const sigPayload = `${this.sessionId}:${this.domain}:${this.nodeIndex}:${targetIdx}:${ciphertextHex}:${ivHex}:${authTagHex}`;
        const signatureHex = signDkgPayload(sigPayload, this.identityPrivateKeyHex);

        const envelope: EncryptedShareEnvelope = {
          type: 'ENCRYPTED_SHARE',
          sessionId: this.sessionId,
          domain: this.domain,
          dealerIndex: this.nodeIndex,
          targetIndex: targetIdx,
          commitmentMatrix: msg.commitmentMatrix,
          encryptedPayload: ciphertextHex,
          ivHex,
          authTagHex,
          senderPublicKeyHex: this.identityPublicKeyHex,
          signatureHex,
          timestamp: Date.now(),
        };

        envelopes.push(envelope);
      } else {
        // Sign non-secret broadcast/point protocol messages (ECHO, READY, PROPOSAL, LEAD_CH)
        const payloadStr = JSON.stringify(msg);
        const hashMsg = `${this.sessionId}:${this.domain}:${this.nodeIndex}:${payloadStr}`;
        const signatureHex = signDkgPayload(hashMsg, this.identityPrivateKeyHex);

        const envelope: SignedProtocolEnvelope = {
          type: 'DKG_PROTOCOL_MSG',
          sessionId: this.sessionId,
          domain: this.domain,
          fromIndex: this.nodeIndex,
          targetIndex: item.targetIndex,
          payload: msg,
          senderPublicKeyHex: this.identityPublicKeyHex,
          signatureHex,
          timestamp: Date.now(),
        };

        envelopes.push(envelope);
      }
    }

    return envelopes;
  }
}
